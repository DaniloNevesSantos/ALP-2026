# a função bool serve para determinar se uma expressão é verdadeira ou falsa.
bool(5 > 3)  # ex. Resulta em True  pois a sentença 5 > 3 é verdadeira.

# a função abs serve para ter o valor absoluto de um número.
abs(-7)  #ex. Resulta em 7 pois o valor absoluto de -7 é 7.

# a função float serve para converter ou ter a possibilidade de ter um número inteiro em um número decimal.
float(5)  # ex. Resulta em 5.0 pois o número inteiro 5 é convertido para o número decimal 5.0

# a função int serve para colocar um número um número inteiro.
int(5)  # ex. o número 5 é considerado um número inteiro.

# a função str serve para converter um número inteiro ou decimal em texto.
str(5)  # ex. "5"  número inteiro  é convertido para texto.

#a função type serve para determinar o tipo de uma variável.
type(5)  # ex. dá com resposta class 'int' pois o númeo 5 é um numero  inteiro.

